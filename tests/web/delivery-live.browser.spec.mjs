import { createRequire } from 'node:module';
import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const require = createRequire(new URL('../../web/package.json', import.meta.url));
const { test, expect } = require('@playwright/test');

test('fresh Python delivery renders exact schedule, moves network focus, validates edits and downloads original ZIP', async ({ page }, testInfo) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: 'Data delivery', exact: true }).click();
  await expect(page.locator('#delivery-status')).toContainText('service ready');
  await expect(page.getByRole('button', { name: 'Plan delivery', exact: true })).toBeEnabled();
  await page.getByLabel('Initial battery energy (Wh)', { exact: true }).fill('');
  await expect(page.getByRole('button', { name: 'Plan delivery', exact: true })).toBeDisabled();
  await expect(page.locator('#delivery-input-errors')).toContainText('finite number');
  await page.getByRole('button', { name: 'Restore declared inputs', exact: true }).click();
  await page.getByLabel('Data ready UTC', { exact: true }).fill('');
  await expect(page.getByRole('button', { name: 'Plan delivery', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Restore declared inputs', exact: true }).click();
  const calculated = page.waitForResponse(response => response.url().endsWith('/research/delivery/analyze'));
  await page.getByRole('button', { name: 'Plan delivery', exact: true }).click();
  const transport = await calculated;
  expect(transport.status()).toBe(200);
  const artifact = await transport.json();
  await expect(page.locator('#delivery-status')).toContainText('Calculated delivery in Python');
  await expect(page.locator('#delivery-outcome')).toContainText(artifact.result.solver_status);
  await expect(page.locator('#delivery-outcome')).toContainText(artifact.result.model_fidelity);
  await expect(page.locator('#delivery-outcome')).toContainText(artifact.result.final_byte_arrival_utc);
  expect(artifact.replay.passed).toBe(true);
  await expect(page.getByRole('heading', { name: 'Exact selected transfers', exact: true })).toBeVisible();
  const first = page.locator('.delivery-focus button').first(); await first.click();
  const contact = artifact.result.contacts.find(item => item.contact_id === artifact.result.allocations[0].contact_id);
  await expect(page.locator('#research-map-status')).toContainText(artifact.scenario.relay_refs.includes(contact.receiver) ? 'Lunar hop at' : 'Moon and Earth endpoints retain Python distances');
  await expect(page.locator('#delivery-resource-readout')).toContainText(artifact.result.allocations[0].source_transmit_interval.start_utc);
  await page.getByRole('button', { name: 'Earth network', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Earth network', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('#research-map-status')).toContainText('Moon and Earth endpoints retain Python distances');
  const pending = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Python run package', exact: true }).click();
  const bytes = await readFile(await (await pending).path());
  expect(bytes.length).toBe(artifact.export.size_bytes);
  expect(createHash('sha256').update(bytes).digest('hex')).toBe(artifact.export.sha256);
  await page.screenshot({ path: testInfo.outputPath('delivery-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByText('Selenographic Observation and Mission Atlas', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  const networkButton = page.getByRole('button', { name: 'Earth network', exact: true });
  await networkButton.scrollIntoViewIfNeeded(); await expect(networkButton).toBeInViewport();
  const packageButton = page.getByRole('button', { name: 'Python run package', exact: true });
  await packageButton.scrollIntoViewIfNeeded(); await expect(packageButton).toBeInViewport();
  const planButton = page.getByRole('button', { name: 'Plan delivery', exact: true });
  await page.keyboard.press('Tab');
  await planButton.focus(); await expect(planButton).toBeFocused();
  expect(await planButton.evaluate(button => getComputedStyle(button).outlineStyle)).not.toBe('none');
  await page.keyboard.press('Tab'); await expect(planButton).not.toBeFocused();
  await expect(page.getByRole('button', { name: 'Use inspected geometry site', exact: true })).toBeFocused();
  await page.screenshot({ path: testInfo.outputPath('delivery-mobile-390.png'), fullPage: true });
  await page.getByLabel('Battery reserve (Wh)', { exact: true }).fill('25');
  await expect(page.locator('#delivery-profiles')).toContainText('reserve 25 Wh');
  await expect(page.getByRole('button', { name: 'Python run package', exact: true })).toBeDisabled();
  await page.getByLabel('Delivery data volume', { exact: true }).fill('');
  await expect(planButton).toBeDisabled();
  await expect(page.locator('#delivery-input-errors')).toContainText('finite number');
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.getByRole('button', { name: 'Inspect geometry inputs', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Geometry', exact: true })).toHaveAttribute('aria-pressed', 'true');
  expect(errors).toEqual([]);
});
