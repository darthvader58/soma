def test_lro_native_source_when_prepared(kernel_root, study):
    source = spacecraft_manifest()
    if source is None or not (kernel_root / source["path"]).is_file():
        pytest.skip("root's pinned reconstructed LRO source not prepared yet")
    study["spacecraft_refs"] = [source["id"]]
    start = source["coverage"]["start_utc"]
    from datetime import timedelta
    from soma.time import parse_utc, format_utc
    study["time"] = {"start_utc": start, "end_utc": format_utc(parse_utc(start) + timedelta(hours=2)), "step_s": 60}
    result = analyze_study(study, data_root=kernel_root)
    spacecraft = result["spacecraft"][0]
    assert spacecraft["input_class"] == "reconstructed_ephemeris"
    assert len(spacecraft["samples"]) == 121
    positions = np.array([state["position_m"] for state in spacecraft["samples"]])
    assert np.ptp(positions[:, 2]) > 1e6
    assert np.all((np.linalg.norm(positions, axis=1) > 1737400) & (np.linalg.norm(positions, axis=1) < 3e6))
    assert result["provenance"]["spacecraft_sources"][0]["manifest"]["sha256"] == source["sha256"]
    broken = deepcopy(source)
    broken["sha256"] = "0" * 64
    with pytest.raises(StudyValidationError, match="SHA256"):
        verify_spacecraft(broken, kernel_root)
    import spiceypy as spice
    handle = spice.dafopr(str(kernel_root / source["path"]))
    try:
        spice.dafbfs(handle)
        segment_count = 0
        while spice.daffna():
            _, integers = spice.dafus(spice.dafgs(), 2, 6)
            assert list(integers[:4]) == [-85, 301, 1, 13]
            segment_count += 1
        assert segment_count > 1
    finally:
        spice.dafcls(handle)
    study["time"]["end_utc"] = format_utc(parse_utc(start) + timedelta(seconds=20))
    study["time"]["step_s"] = 10
    sampled = analyze_study(study, data_root=kernel_root)["spacecraft"][0]["samples"]
    finite_difference = (np.array(sampled[2]["position_m"]) - sampled[0]["position_m"]) / 20
    # The finite-step derivative tests rotating-frame velocity semantics. It is
    # not an independent validation of the reconstructed mission ephemeris.
    np.testing.assert_allclose(sampled[1]["velocity_m_s"], finite_difference, atol=0.05, rtol=0)
    study["time"] = {"start_utc": "2026-06-14T23:59:50Z", "end_utc": "2026-06-15T00:00:10Z", "step_s": 10}
    with pytest.raises(StudyValidationError, match="declared coverage"):
        analyze_study(study, data_root=kernel_root)
