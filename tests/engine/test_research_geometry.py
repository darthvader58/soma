from soma.research import (StudyCancelled, StudyValidationError, analyze_study,
                           runtime_capabilities, study_sha256)
from soma.research.spacecraft import spacecraft_manifest, verify_spacecraft
from soma.validation import validate_document


@pytest.fixture
def kernel_root():
    root = Path(os.environ.get("SOMA_RESEARCH_DATA_ROOT", os.environ.get("SOMA_PHASE2_DATA_ROOT", "/private/tmp/soma-phase2-data")))
    if not all((root / name).is_file() for name in ("de421.bsp", "naif0012.tls", "moon_080317.tf", "moon_pa_de421_1900-2050.bpc")):
        pytest.skip("externally acquired matched DE421 kernels unavailable")
    return root


@pytest.fixture
def study():
    return {"study_version": "1.0.0", "analysis_type": "geometry", "frame": "MOON_ME_DE421",
            "reference_radius_m": 1737400, "surface_model": "reference_sphere",
            "sites": [{"id": "custom-a", "name": "Uncaptured custom location", "latitude_deg": 14.25,
                       "longitude_deg_east": 51.75, "elevation_m": -123,
                       "antenna_height_m": 3, "panel_height_m": 0.75}],
            "time": {"start_utc": "2024-01-08T00:00:00Z", "end_utc": "2024-01-08T08:00:00Z", "step_s": 3600},
            "spacecraft_refs": []}


def test_new_site_and_date_compute_changed_native_geometry(kernel_root, study):
    result = analyze_study(study, data_root=kernel_root)
    validate_document(result, "study-result")
    assert result["study_sha256"] == study_sha256(study)
    assert result["request"] == study
    assert result["spacecraft"] == []
    assert len(result["epochs_utc"]) == 9
    assert set(item["role"] for item in result["provenance"]["kernels"]) == {
        "leap_seconds", "lunar_frame", "lunar_orientation", "planetary_ephemeris"}
    sun = result["bodies"][0]["samples"]
    assert np.linalg.norm(np.array(sun[-1]["position_m"]) - sun[0]["position_m"]) > 1e8
    site = result["sites"][0]
    assert site["quality"]["terrain_visibility"] == "not_evaluated"
    assert site["quality"]["power"] == "not_evaluated"
    assert np.linalg.norm(np.array(site["antenna_position_m"]) - site["position_m"]) == pytest.approx(3)
    for target, observer in (("sun", "panel_position_m"), ("earth", "antenna_position_m")):
        body = next(body for body in result["bodies"] if body["id"].lower() == target)
        offset = np.array(body["samples"][0]["position_m"]) - site[observer]
        np.testing.assert_allclose(site["samples"][0][target]["direction_moon_fixed"], offset / np.linalg.norm(offset), atol=1e-15)
    changed = deepcopy(study)
    changed["sites"][0]["longitude_deg_east"] = -42.5
    changed["time"] = {"start_utc": "2024-02-08T00:00:00Z", "end_utc": "2024-02-08T08:00:00Z", "step_s": 3600}
    other = analyze_study(changed, data_root=kernel_root)
    assert other["study_sha256"] != result["study_sha256"]
    assert abs(other["sites"][0]["samples"][0]["sun"]["elevation_deg"] - site["samples"][0]["sun"]["elevation_deg"]) > 1
    assert analyze_study(study, data_root=kernel_root) == result


def test_published_naif_vector_and_native_six_dimensional_derivative(kernel_root, study):
    # Reference is printed in NAIF's moon_080317.tf, not generated by SOMA.
    study["time"] = {"start_utc": "2008-03-17T20:09:50Z", "end_utc": "2008-03-17T20:10:10Z", "step_s": 10}
    result = analyze_study(study, data_root=kernel_root)
    earth = result["bodies"][1]["samples"]
    np.testing.assert_allclose(earth[1]["position_m"], [379892825, 33510118, -12661527.8], atol=0.6, rtol=0)
    central_velocity = (np.array(earth[2]["position_m"]) - earth[0]["position_m"]) / 20
    np.testing.assert_allclose(earth[1]["velocity_m_s"], central_velocity, rtol=0, atol=2e-5)


def test_native_coverage_not_november_or_earth_orientation_limited(kernel_root, study):
    study["time"] = {"start_utc": "1950-02-01T00:00:00Z", "end_utc": "1950-02-15T00:00:00Z", "step_s": 86400}
    assert len(analyze_study(study, data_root=kernel_root)["epochs_utc"]) == 15
    study["time"] = {"start_utc": "2051-01-01T00:00:00Z", "end_utc": "2051-01-01T00:01:00Z", "step_s": 60}
    with pytest.raises(StudyValidationError, match="PCK"):
        analyze_study(study, data_root=kernel_root)
    caps = runtime_capabilities(data_root=kernel_root)
    assert caps["ready"]
    assert caps["coverage"]["start_utc"].startswith("1899")
    assert caps["coverage"]["end_utc"].startswith("2050")
    assert caps["limits"]["max_duration_days"] == 31


def test_exact_poles_use_declared_basis(kernel_root, study):
    study["sites"] = [{**study["sites"][0], "id": str(lat), "latitude_deg": lat} for lat in (-90, 90)]
    result = analyze_study(study, data_root=kernel_root)
    for site in result["sites"]:
        assert site["position_m"][:2] == [0, 0]
        assert site["quality"]["pole_reference_meridian_deg_east"] == 0
        assert all(np.isfinite(sample["sun"]["azimuth_deg"]) for sample in site["samples"])


def test_cancellation_restores_external_kernel_pool(kernel_root, study):
    import spiceypy as spice
    event = Event()
    spice.pdpool("SOMA_RESEARCH_EXTERNAL_TEST", [73.5])
    before = [spice.kdata(i, "ALL")[:3] for i in range(spice.ktotal("ALL"))]

    def cancel(progress):
        if progress["stage"] == "geometry" and progress["completed_epochs"]:
            event.set()

    try:
        with pytest.raises(StudyCancelled):
            analyze_study(study, data_root=kernel_root, progress=cancel, cancel_event=event)
        assert [spice.kdata(i, "ALL")[:3] for i in range(spice.ktotal("ALL"))] == before
        assert list(spice.gdpool("SOMA_RESEARCH_EXTERNAL_TEST", 0, 1)) == [73.5]
        with pytest.raises(StudyCancelled):
            analyze_study(study, data_root=kernel_root, cancel_event=event)
    finally:
        spice.dvpool("SOMA_RESEARCH_EXTERNAL_TEST")


